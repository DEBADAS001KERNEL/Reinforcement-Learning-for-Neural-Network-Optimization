import argparse, copy, random, time
from collections import deque
from pathlib import Path
import numpy as np
import matplotlib.pyplot as plt
from PIL import Image, ImageOps
import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.utils.data import DataLoader, random_split
from torchvision import datasets, transforms

DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
MODEL_DIR = Path("saved_mnist_models")
MODEL_DIR.mkdir(parents=True, exist_ok=True)
MEAN, STD = (0.1307,), (0.3081,)
BASE_LR, MOMENTUM = 0.01, 0.9
PROBE_POOL, PROBE_BATCH = 2048, 512


def set_seed(seed):
    random.seed(seed); np.random.seed(seed); torch.manual_seed(seed)
    if torch.cuda.is_available(): torch.cuda.manual_seed_all(seed)


# ------------------------------------------------------------------- data
def load_data(batch_size, seed):
    tfm = transforms.Compose([transforms.ToTensor(), transforms.Normalize(MEAN, STD)])
    full = datasets.MNIST("./data", train=True, download=True, transform=tfm)
    test = datasets.MNIST("./data", train=False, download=True, transform=tfm)
    train, val = random_split(full, [50000, 10000],
                              generator=torch.Generator().manual_seed(seed))
    train_loader = DataLoader(train, batch_size=batch_size, shuffle=True, num_workers=0,
                              generator=torch.Generator().manual_seed(seed))
    val_loader = DataLoader(val, batch_size=512, shuffle=False, num_workers=0)
    test_loader = DataLoader(test, batch_size=512, shuffle=False, num_workers=0)
    # probe pool: training images the DQN uses to judge each step (reward)
    px = torch.stack([train[i][0] for i in range(PROBE_POOL)]).to(DEVICE)
    py = torch.tensor([train[i][1] for i in range(PROBE_POOL)]).to(DEVICE)
    return train_loader, val_loader, test_loader, test, (px, py)


class SmallCNN(nn.Module):
    def __init__(self):
        super().__init__()
        self.conv1 = nn.Conv2d(1, 16, 3, padding=1)
        self.conv2 = nn.Conv2d(16, 32, 3, padding=1)
        self.pool = nn.MaxPool2d(2)
        self.fc1 = nn.Linear(32 * 7 * 7, 64)
        self.fc2 = nn.Linear(64, 10)

    def forward(self, x):
        x = self.pool(F.relu(self.conv1(x)))
        x = self.pool(F.relu(self.conv2(x)))
        x = torch.flatten(x, 1)
        return self.fc2(F.relu(self.fc1(x)))


def fresh_model(seed):
    set_seed(seed)                      # same seed -> identical starting weights
    return SmallCNN().to(DEVICE)


@torch.no_grad()
def evaluate(model, loader):
    model.eval(); loss_sum = correct = total = 0
    for x, y in loader:
        x, y = x.to(DEVICE), y.to(DEVICE)
        logits = model(x)
        loss_sum += F.cross_entropy(logits, y, reduction="sum").item()
        correct += (logits.argmax(1) == y).sum().item()
        total += y.numel()
    return loss_sum / max(total, 1), correct / max(total, 1)


def flat_params(model):
    return torch.cat([p.detach().reshape(-1) for p in model.parameters()])


def flat_grads(model):
    return torch.cat([p.grad.detach().reshape(-1) for p in model.parameters()])


# ------------------------------------------------------------ teacher (minimum proxy)
def train_teacher(train_loader, epochs, seed, limit):
    model = fresh_model(seed)
    opt = torch.optim.Adam(model.parameters(), lr=1e-3)
    for ep in range(epochs):
        model.train()
        for i, (x, y) in enumerate(train_loader):
            if limit and i >= limit: break
            x, y = x.to(DEVICE), y.to(DEVICE)
            opt.zero_grad(set_to_none=True)
            F.cross_entropy(model(x), y).backward(); opt.step()
    print(f"  teacher ready ({epochs} Adam epochs); this is the 'minimum' proxy")
    return flat_params(model).clone()


# ----------------------------------------------------------------- baselines
def train_baseline(name, train_loader, val_loader, test_loader, epochs, seed, limit):
    model = fresh_model(seed)
    opt = (torch.optim.SGD(model.parameters(), lr=BASE_LR, momentum=MOMENTUM)
           if name == "SGD" else torch.optim.Adam(model.parameters(), lr=1e-3))
    best_acc, best_w = -1, copy.deepcopy(model.state_dict())
    hist = {"val_acc": []}; start = time.perf_counter()
    for ep in range(epochs):
        model.train(); loss_sum = n = 0
        for i, (x, y) in enumerate(train_loader):
            if limit and i >= limit: break
            x, y = x.to(DEVICE), y.to(DEVICE)
            opt.zero_grad(set_to_none=True)
            loss = F.cross_entropy(model(x), y); loss.backward(); opt.step()
            loss_sum += loss.item() * y.size(0); n += y.size(0)
        _, va = evaluate(model, val_loader); hist["val_acc"].append(va)
        if va > best_acc: best_acc, best_w = va, copy.deepcopy(model.state_dict())
        print(f"  {name:12} epoch {ep+1}/{epochs} train_loss={loss_sum/max(n,1):.4f} val_acc={va*100:.2f}%")
    model.load_state_dict(best_w)
    path = MODEL_DIR / f"mnist_{name.lower()}.pth"; torch.save(model.state_dict(), path)
    tl, ta = evaluate(model, test_loader)
    return model, tl, ta, hist, time.perf_counter() - start, path


# --------------------------------------------------------------------- DQN
MULTS = [0.0, 0.25, 0.5, 1.0, 1.5, 2.0, 3.0]     # multiplier on BASE_LR


class Replay:
    def __init__(self, capacity=20000): self.data = deque(maxlen=capacity)
    def add(self, *t): self.data.append(t)
    def sample(self, n):
        s, a, r, ns, d = zip(*random.sample(self.data, n))
        return (np.asarray(s, np.float32), np.asarray(a, np.int64),
                np.asarray(r, np.float32), np.asarray(ns, np.float32),
                np.asarray(d, np.float32))
    def __len__(self): return len(self.data)


class QNet(nn.Module):
    def __init__(self, n_in, n_act):
        super().__init__()
        self.net = nn.Sequential(nn.Linear(n_in, 64), nn.ReLU(),
                                 nn.Linear(64, 64), nn.ReLU(), nn.Linear(64, n_act))
    def forward(self, x): return self.net(x)


class DQNAgent:
    def __init__(self, n_in):
        self.gamma, self.batch_size, self.learn_steps = 0.95, 64, 0
        self.online = QNet(n_in, len(MULTS)).to(DEVICE)
        self.target = copy.deepcopy(self.online).to(DEVICE)
        self.opt = torch.optim.Adam(self.online.parameters(), lr=1e-3)
        self.replay = Replay()

    def act(self, state, epsilon):
        if random.random() < epsilon: return random.randrange(len(MULTS))
        with torch.no_grad():
            s = torch.tensor(state, dtype=torch.float32, device=DEVICE).unsqueeze(0)
            return int(self.online(s).argmax(1).item())

    def learn(self):
        if len(self.replay) < max(self.batch_size, 200): return
        s, a, r, ns, d = self.replay.sample(self.batch_size)
        s, ns = torch.tensor(s, device=DEVICE), torch.tensor(ns, device=DEVICE)
        a = torch.tensor(a, device=DEVICE).unsqueeze(1)
        r, d = torch.tensor(r, device=DEVICE), torch.tensor(d, device=DEVICE)
        q = self.online(s).gather(1, a).squeeze(1)
        with torch.no_grad():                                  # Double-DQN target
            na = self.online(ns).argmax(1, keepdim=True)
            nq = self.target(ns).gather(1, na).squeeze(1)
            y = r + self.gamma * nq * (1 - d)
        loss = F.smooth_l1_loss(q, y)
        self.opt.zero_grad(set_to_none=True); loss.backward()
        nn.utils.clip_grad_norm_(self.online.parameters(), 5.0); self.opt.step()
        self.learn_steps += 1
        if self.learn_steps % 200 == 0:
            self.target.load_state_dict(self.online.state_dict())


def make_state(loss, prev_loss, gn, progress, extras=None):
    delta = 0.0 if prev_loss is None else prev_loss - loss
    base = [np.clip(loss, 0, 10) / 10, np.clip(delta, -2, 2) / 2,
            np.tanh(np.log1p(max(0.0, gn))), progress]
    return np.array(base + (extras or []), dtype=np.float32)


@torch.no_grad()
def probe_loss(model, probe, idx):
    px, py = probe
    return F.cross_entropy(model(px[idx]), py[idx]).item()


def train_dqn(mode, teacher_vec, probe, train_loader, val_loader, test_loader,
              epochs, seed, limit):
    use_teacher = (mode == "teacher")
    label = "DQN+Teacher" if use_teacher else "DQN-Blind"
    model = fresh_model(seed)
    params = list(model.parameters())
    bufs = [torch.zeros_like(p) for p in params]
    agent = DQNAgent(4 + (3 if use_teacher else 0))
    per_epoch = min(len(train_loader), limit if limit else len(train_loader))
    total = epochs * per_epoch
    d0 = (flat_params(model) - teacher_vec).norm().item() if use_teacher else 1.0
    prev_dist = d0
    best_acc, best_w = -1, copy.deepcopy(model.state_dict())
    hist = {"val_acc": [], "mean_mult": []}
    start, step, prev_probe, pending = time.perf_counter(), 0, None, None

    for ep in range(epochs):
        model.train(); loss_sum = n = 0; mult_sum = 0.0
        for i, (x, y) in enumerate(train_loader):
            if limit and i >= limit: break
            x, y = x.to(DEVICE), y.to(DEVICE)
            for p in params: p.grad = None
            loss = F.cross_entropy(model(x), y); loss.backward()
            g = flat_grads(model); gn = g.norm().item()
            idx = torch.randint(0, PROBE_POOL, (PROBE_BATCH,), device=DEVICE)
            before = probe_loss(model, probe, idx)             # judged on a different batch

            extras = None
            if use_teacher:
                w = flat_params(model); to_min = teacher_vec - w
                dist = to_min.norm().item()
                cos = float(torch.dot(-g, to_min) / (g.norm() * to_min.norm() + 1e-12))
                extras = [min(dist / d0, 2.0), cos,
                          float(np.clip((prev_dist - dist) / d0 * 20, -1, 1))]
                prev_dist = dist
            state = make_state(before, prev_probe, gn, step / max(1, total), extras)

            if pending is not None:                            # finish previous transition
                agent.replay.add(pending[0], pending[1], pending[2], state, 0.0)
                agent.learn()

            epsilon = max(0.05, 1.0 - step / (0.7 * total))
            ai = agent.act(state, epsilon); mult = MULTS[ai]
            with torch.no_grad():                              # SGD-momentum step, scaled
                for p, b in zip(params, bufs):
                    b.mul_(MOMENTUM).add_(p.grad)
                    p.add_(b, alpha=-BASE_LR * mult)
            after = probe_loss(model, probe, idx)

            reward = float(np.clip((before - after) * 5, -1, 1)) - 0.002
            if use_teacher:
                new_dist = (flat_params(model) - teacher_vec).norm().item()
                reward += 0.5 * float(np.clip((dist - new_dist) / (dist + 1e-12) * 10, -1, 1))
            pending = (state, ai, reward)
            prev_probe = after
            loss_sum += loss.item() * y.size(0); n += y.size(0)
            mult_sum += mult; step += 1

        _, va = evaluate(model, val_loader); hist["val_acc"].append(va)
        hist["mean_mult"].append(mult_sum / max(1, per_epoch))
        if va > best_acc: best_acc, best_w = va, copy.deepcopy(model.state_dict())
        print(f"  {label:12} epoch {ep+1}/{epochs} train_loss={loss_sum/max(n,1):.4f} "
              f"val_acc={va*100:.2f}% eps={epsilon:.2f} mean_mult={hist['mean_mult'][-1]:.2f}")

    model.load_state_dict(best_w)
    tag = "dqn_teacher" if use_teacher else "dqn_blind"
    path = MODEL_DIR / f"mnist_{tag}.pth"; torch.save(model.state_dict(), path)
    torch.save(agent.online.state_dict(), MODEL_DIR / f"controller_{tag}.pth")
    tl, ta = evaluate(model, test_loader)
    return model, tl, ta, hist, time.perf_counter() - start, path


# ------------------------------------------------------------ image predict
def prepare_image(path):
    img = ImageOps.autocontrast(Image.open(path).convert("L"))
    if np.asarray(img).mean() > 127: img = ImageOps.invert(img)
    arr = np.asarray(img)
    bbox = Image.fromarray((arr > 25).astype(np.uint8) * 255).getbbox()
    if bbox: img = img.crop(bbox)
    img.thumbnail((20, 20), Image.Resampling.LANCZOS)
    canvas = Image.new("L", (28, 28), 0)
    canvas.paste(img, ((28 - img.width) // 2, (28 - img.height) // 2))
    x = transforms.Normalize(MEAN, STD)(transforms.ToTensor()(canvas)).unsqueeze(0)
    return canvas, x


@torch.no_grad()
def predict(model, x):
    model.eval()
    return F.softmax(model(x.to(DEVICE)), dim=1)[0].cpu().numpy()


def show_predictions(models, x, display_image, true_label=None):
    names = list(models)
    probs = {n: predict(m, x) for n, m in models.items()}
    fig = plt.figure(figsize=(15, 7))
    gs = fig.add_gridspec(2, len(names) + 1, height_ratios=[1, 1.2])
    ax = fig.add_subplot(gs[0, 0]); ax.imshow(display_image, cmap="gray")
    ax.set_title("Input" + (f"\nTrue: {true_label}" if true_label is not None else "")); ax.axis("off")
    for i, n in enumerate(names):
        ax = fig.add_subplot(gs[0, i + 1]); p = probs[n]; k = int(p.argmax())
        ax.imshow(display_image, cmap="gray")
        ax.set_title(f"{n}\npred {k} | {p[k]*100:.1f}%"); ax.axis("off")
    ax = fig.add_subplot(gs[1, :]); digits = np.arange(10); w = 0.8 / len(names)
    for i, n in enumerate(names):
        ax.bar(digits + (i - (len(names) - 1) / 2) * w, probs[n] * 100, w, label=n)
    ax.set_xticks(digits); ax.set_xlabel("Digit"); ax.set_ylabel("Softmax score (%)")
    ax.legend(); ax.grid(axis="y", alpha=.25)
    fig.tight_layout(); fig.savefig("mnist_all_algo_predictions.png", dpi=160); plt.show()
    print("\nIMAGE PREDICTIONS")
    for n, p in probs.items():
        print(f"{n:12} -> digit {int(p.argmax())}, score {p.max()*100:.2f}%")


# --------------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--epochs", type=int, default=8)
    ap.add_argument("--teacher-epochs", type=int, default=3)
    ap.add_argument("--runs", type=int, default=1)
    ap.add_argument("--batch-size", type=int, default=128)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--max-train-batches", type=int, default=0)
    ap.add_argument("--image", type=str, default=None)
    args, _ = ap.parse_known_args()
    if min(args.epochs, args.teacher_epochs, args.runs, args.batch_size) < 1 or args.max_train_batches < 0:
        raise ValueError("epochs/runs/batch-size must be positive.")
    print("Device:", DEVICE)

    names = ["SGD", "Adam", "DQN-Blind", "DQN+Teacher"]
    scores = {n: {"loss": [], "acc": [], "sec": []} for n in names}
    last_models, last_hist = {}, {}
    for run in range(args.runs):
        seed = args.seed + run
        print(f"\n========== RUN {run+1}/{args.runs} (seed={seed}) ==========")
        tr, va, te, test_ds, probe = load_data(args.batch_size, seed)
        print("\nTraining teacher (minimum proxy)...")
        teacher_vec = train_teacher(tr, args.teacher_epochs, seed, args.max_train_batches)
        for name in names:
            print(f"\nTraining {name}...")
            if name.startswith("DQN"):
                mode = "teacher" if name == "DQN+Teacher" else "blind"
                out = train_dqn(mode, teacher_vec, probe, tr, va, te,
                                args.epochs, seed, args.max_train_batches)
            else:
                out = train_baseline(name, tr, va, te, args.epochs, seed, args.max_train_batches)
            model, tl, ta, hist, sec, path = out
            scores[name]["loss"].append(tl); scores[name]["acc"].append(ta); scores[name]["sec"].append(sec)
            last_models[name], last_hist[name] = model, hist
            print(f"TEST {name}: loss={tl:.4f} acc={ta*100:.2f}% time={sec:.1f}s  (saved {path})")

    print("\n========== FINAL TEST SUMMARY (mean +/- std over runs) ==========")
    for n in names:
        a, l, t = scores[n]["acc"], scores[n]["loss"], scores[n]["sec"]
        print(f"{n:12} | acc {np.mean(a)*100:.2f}% +/- {np.std(a)*100:.2f}% | "
              f"loss {np.mean(l):.4f} +/- {np.std(l):.4f} | time {np.mean(t):.0f}s")
    if args.runs == 1:
        print("(only 1 run: differences of a few tenths of a percent are noise; use --runs 3+)")

    plt.figure(figsize=(8, 5))
    for n in names:
        v = np.asarray(last_hist[n]["val_acc"]) * 100
        plt.plot(np.arange(1, len(v) + 1), v, marker="o", label=n)
    plt.xlabel("Epoch"); plt.ylabel("Validation accuracy (%)")
    plt.title("MNIST validation accuracy"); plt.grid(True, alpha=.3); plt.legend()
    plt.tight_layout(); plt.savefig("mnist_training_comparison.png", dpi=160); plt.show()

    if args.image:
        display, x = prepare_image(args.image); truth = None
    else:
        set_seed(args.seed); idx = random.randrange(len(test_ds))
        x, lab = test_ds[idx]; truth = int(lab)
        display = (x.squeeze(0) * STD[0] + MEAN[0]).clamp(0, 1).cpu().numpy()
        x = x.unsqueeze(0)                      # (1,28,28) -> (1,1,28,28) batch
    show_predictions(last_models, x, display, truth)
    print("\nFinished. Models are in ./saved_mnist_models/")


if __name__ == "__main__":
    main()

"""
STRESS TEST: where does an RL-controlled optimizer help?

Install: pip install torch torchvision matplotlib numpy

Smoke test (about 1-2 min):
  python rl_optimizer_stress_test.py --epochs 1 --meta-episodes 2 --meta-batches 20 \
         --max-train-batches 30 --lr-scales 1

Test 1  bad learning rates on an easy task:
  python rl_optimizer_stress_test.py --dataset mnist --lr-scales 0.1,1,10

Test 2  HARD: harder images + 30% wrong labels + bad learning rates:
  python rl_optimizer_stress_test.py --dataset cifar10 --label-noise 0.3 --lr-scales 0.1,1,10

Methods (same CNN, same start weights, same data order):
  SGD         lr = 0.01 x scale, momentum 0.9
  Adam        lr = 0.001 x scale
  DQN-Online  DQN picks a multiplier on the SGD-momentum step; learns only
              during this single run (few decisions to learn from)
  DQN-Meta    SAME controller, but first trained over many short runs with
              randomly mis-set learning rates (0.03x to 30x), then FROZEN.
              This is the "learning to optimize" setup.

Notes:
  - "lr scale" multiplies the starting learning rate of every method, so
    scale 0.1 = far too small, scale 10 = far too large.
  - The DQN controllers have a safety rollback: if a step makes the loss
    explode, the step is undone and the agent gets reward -1. SGD/Adam
    have no rollback, so they can diverge. Rollbacks are counted/printed.
  - DQN controllers use extra forward passes (probe batches) every step.
  - Label noise: that fraction of TRAINING labels is replaced by random
    labels. Validation/test labels stay clean.
"""

