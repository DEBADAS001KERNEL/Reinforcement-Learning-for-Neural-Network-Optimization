class Replay:
    def __init__(self, capacity=30000): self.data = deque(maxlen=capacity)
    def add(self, *t): self.data.append(t)
    def sample(self, n):
        s, a, r, ns, d = zip(*random.sample(self.data, n))
        return (np.asarray(s, np.float32), np.asarray(a, np.int64), np.asarray(r, np.float32),
                np.asarray(ns, np.float32), np.asarray(d, np.float32))
    def __len__(self): return len(self.data)


class QNet(nn.Module):
    def __init__(self):
        super().__init__()
        self.net = nn.Sequential(nn.Linear(STATE_DIM, 64), nn.ReLU(),
                                 nn.Linear(64, 64), nn.ReLU(), nn.Linear(64, len(MULTS)))
    def forward(self, x): return self.net(x)


class DQNAgent:
    def __init__(self):
        self.gamma, self.batch_size, self.learn_steps = 0.95, 64, 0
        self.online = QNet().to(DEVICE)
        self.target = copy.deepcopy(self.online).to(DEVICE)
        self.opt = torch.optim.Adam(self.online.parameters(), lr=1e-3)
        self.replay = Replay()

    def act(self, state, epsilon):
        if random.random() < epsilon: return random.randrange(len(MULTS))
        with torch.no_grad():
            s = torch.tensor(state, dtype=torch.float32, device=DEVICE).unsqueeze(0)
            return int(self.online(s).argmax(1).item())

    def learn(self):
        if len(self.replay) < max(self.batch_size, 200): return
        s, a, r, ns, d = self.replay.sample(self.batch_size)
        s, ns = torch.tensor(s, device=DEVICE), torch.tensor(ns, device=DEVICE)
        a = torch.tensor(a, device=DEVICE).unsqueeze(1)
        r, d = torch.tensor(r, device=DEVICE), torch.tensor(d, device=DEVICE)
        q = self.online(s).gather(1, a).squeeze(1)
        with torch.no_grad():                                   # Double-DQN target
            na = self.online(ns).argmax(1, keepdim=True)
            y = r + self.gamma * self.target(ns).gather(1, na).squeeze(1) * (1 - d)
        loss = F.smooth_l1_loss(q, y)
        self.opt.zero_grad(set_to_none=True); loss.backward()
        nn.utils.clip_grad_norm_(self.online.parameters(), 5.0); self.opt.step()
        self.learn_steps += 1
        if self.learn_steps % 200 == 0:
            self.target.load_state_dict(self.online.state_dict())


def make_state(loss, prev_loss, gn, progress, lr_feat, last_a):
    delta = 0.0 if prev_loss is None else prev_loss - loss
    return np.array([np.clip(loss, 0, 10) / 10, np.clip(delta, -2, 2) / 2,
                     np.tanh(np.log1p(max(0.0, gn))), progress, lr_feat, last_a],
                    dtype=np.float32)


@torch.no_grad()
def probe_loss(model, probe, idx):
    px, py = probe
    return F.cross_entropy(model(px[idx]), py[idx]).item()


def run_dqn(agent, model, loader, probe, epochs, max_batches, base_lr, eps_fn, learn,
            step_offset=0, val_loader=None, label="DQN"):
    """One training run where the agent picks the lr multiplier at every step."""
    params = list(model.parameters())
    bufs = [torch.zeros_like(p) for p in params]
    per_epoch = min(len(loader), max_batches or len(loader))
    run_steps = max(1, epochs * per_epoch)
    lr_feat = float(np.clip(math.log10(base_lr / BASE_LR) / 2, -1.5, 1.5))
    best_acc, best_w = -1, None
    hist = {"val_acc": [], "mean_mult": []}
    prev_probe = pending = None
    step = last_a = rollbacks = 0
    last_after = float("nan")

    for ep in range(epochs):
        model.train(); loss_sum = n = 0; mult_sum = 0.0; eps = eps_fn(step_offset + step)
        for i, (x, y) in enumerate(loader):
            if max_batches and i >= max_batches: break
            x, y = x.to(DEVICE), y.to(DEVICE)
            for p in params: p.grad = None
            loss = F.cross_entropy(model(x), y); loss.backward()
            gn = torch.sqrt(sum((p.grad ** 2).sum() for p in params)).item()
            idx = torch.randint(0, PROBE_POOL, (PROBE_BATCH,), device=DEVICE)
            before = probe_loss(model, probe, idx)               # judged on a different batch
            state = make_state(before, prev_probe, gn, step / run_steps, lr_feat,
                               last_a / (len(MULTS) - 1))
            if learn and pending is not None:
                agent.replay.add(pending[0], pending[1], pending[2], state, 0.0)
                agent.learn()

            eps = eps_fn(step_offset + step)
            ai = agent.act(state, eps); mult = MULTS[ai]
            snap = [p.detach().clone() for p in params]
            with torch.no_grad():                                # SGD-momentum step, scaled
                for p, b in zip(params, bufs):
                    b.mul_(MOMENTUM).add_(p.grad)
                    p.add_(b, alpha=-base_lr * mult)
            after = probe_loss(model, probe, idx)
            if (not math.isfinite(after)) or after > before + 3.0:   # safety rollback
                with torch.no_grad():
                    for p, s in zip(params, snap): p.copy_(s)
                    for b in bufs: b.zero_()
                after, reward = before, -1.0
                rollbacks += 1
            else:
                reward = float(np.clip((before - after) * 5, -1, 1)) - 0.002
            if learn: pending = (state, ai, reward)
            prev_probe, last_a, last_after = after, ai, after
            loss_sum += loss.item() * y.size(0); n += y.size(0)
            mult_sum += mult; step += 1

        hist["mean_mult"].append(mult_sum / max(1, per_epoch))
        if val_loader is not None:
            _, a = evaluate(model, val_loader); hist["val_acc"].append(a)
            if a > best_acc: best_acc, best_w = a, copy.deepcopy(model.state_dict())
            print(f"  {label:10} lr={base_lr:.5f} epoch {ep+1}/{epochs} train_loss={loss_sum/max(n,1):.4f} "
                  f"val_acc={a*100:.2f}% eps={eps:.2f} mean_mult={hist['mean_mult'][-1]:.2f} "
                  f"rollbacks={rollbacks}")
    if best_w is not None: model.load_state_dict(best_w)
    return hist, rollbacks, step, last_after


def meta_train(args, tr, probe, info, seed):
    """Train ONE controller over many short runs with randomly mis-set learning rates."""
    agent = DQNAgent()
    total = max(1, args.meta_episodes * args.meta_batches)
    rng = random.Random(seed)
    offset = 0
    print(f"\nMeta-training controller: {args.meta_episodes} runs x {args.meta_batches} batches, "
          f"lr scale drawn from 0.03x..30x")
    for e in range(args.meta_episodes):
        scale = 10 ** rng.uniform(-1.5, 1.5)
        model = fresh_model(10_000 + seed * 100 + e, info)
        eps_fn = lambda s, off=0: max(0.05, 1.0 - s / (0.7 * total))
        _, rb, steps, final = run_dqn(agent, model, tr, probe, 1, args.meta_batches,
                                      BASE_LR * scale, eps_fn, True, step_offset=offset)
        offset += steps
        print(f"  meta-run {e+1:2d}/{args.meta_episodes}: lr scale {scale:6.2f}x | "
              f"final probe loss {final:.3f} | rollbacks {rb}")
    torch.save(agent.online.state_dict(), OUT_DIR / "meta_controller.pth")
    return agent


