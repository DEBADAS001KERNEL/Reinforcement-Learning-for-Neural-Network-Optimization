def train_baseline(name, scale, tr, va, te, epochs, seed, info, limit):
    model = fresh_model(seed, info)
    lr = (BASE_LR if name == "SGD" else ADAM_LR) * scale
    opt = (torch.optim.SGD(model.parameters(), lr=lr, momentum=MOMENTUM) if name == "SGD"
           else torch.optim.Adam(model.parameters(), lr=lr))
    best_acc, best_w, diverged = -1, None, False
    start = time.perf_counter()
    for ep in range(epochs):
        model.train(); loss_sum = n = 0
        for i, (x, y) in enumerate(tr):
            if limit and i >= limit: break
            x, y = x.to(DEVICE), y.to(DEVICE)
            opt.zero_grad(set_to_none=True)
            loss = F.cross_entropy(model(x), y)
            if not torch.isfinite(loss): diverged = True; break
            loss.backward(); opt.step()
            loss_sum += loss.item() * y.size(0); n += y.size(0)
        if diverged:
            print(f"  {name:10} lr={lr:.5f} DIVERGED (loss became NaN/inf) in epoch {ep+1}")
            break
        _, a = evaluate(model, va)
        if a > best_acc: best_acc, best_w = a, copy.deepcopy(model.state_dict())
        print(f"  {name:10} lr={lr:.5f} epoch {ep+1}/{epochs} train_loss={loss_sum/max(n,1):.4f} val_acc={a*100:.2f}%")
    if best_w is not None and not diverged: model.load_state_dict(best_w)
    tl, ta = evaluate(model, te)
    return ta, tl, time.perf_counter() - start, ("diverged" if diverged else "")


