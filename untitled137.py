# ------------------------------------------------------------------- data
class Relabeled(Dataset):
    def __init__(self, sub, labels): self.sub, self.labels = sub, labels
    def __len__(self): return len(self.sub)
    def __getitem__(self, i): return self.sub[i][0], int(self.labels[i])


def load_data(name, batch_size, seed, label_noise):
    cls, mean, std, ch, size = DATASETS[name]
    tfm = transforms.Compose([transforms.ToTensor(), transforms.Normalize(mean, std)])
    full = cls("./data", train=True, download=True, transform=tfm)
    test = cls("./data", train=False, download=True, transform=tfm)
    n_val = 10000
    train_sub, val_sub = random_split(full, [len(full) - n_val, n_val],
                                      generator=torch.Generator().manual_seed(seed))
    labels = torch.as_tensor(full.targets)[torch.as_tensor(train_sub.indices)].clone()
    if label_noise > 0:
        g = torch.Generator().manual_seed(seed + 999)
        flip = torch.rand(len(labels), generator=g) < label_noise
        labels[flip] = torch.randint(0, 10, (int(flip.sum()),), generator=g)
        print(f"  label noise: {flip.float().mean()*100:.1f}% of training labels re-drawn at random")
    train = Relabeled(train_sub, labels)
    tr = DataLoader(train, batch_size=batch_size, shuffle=True, num_workers=0,
                    generator=torch.Generator().manual_seed(seed))
    va = DataLoader(val_sub, batch_size=512, shuffle=False, num_workers=0)
    te = DataLoader(test, batch_size=512, shuffle=False, num_workers=0)
