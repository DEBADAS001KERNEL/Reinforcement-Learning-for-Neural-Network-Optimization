def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", choices=list(DATASETS), default="mnist")
    ap.add_argument("--epochs", type=int, default=5)
    ap.add_argument("--runs", type=int, default=3)
    ap.add_argument("--batch-size", type=int, default=128)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--lr-scales", type=str, default="0.1,1,10")
    ap.add_argument("--label-noise", type=float, default=0.0)
    ap.add_argument("--meta-episodes", type=int, default=16)
    ap.add_argument("--meta-batches", type=int, default=300)
    ap.add_argument("--meta-epochs", type=int, default=2)
    ap.add_argument("--max-train-batches", type=int, default=0)
    args, _ = ap.parse_known_args()
    scales = [float(s) for s in args.lr_scales.split(",")]
    if min(args.epochs, args.runs, args.batch_size) < 1 or not 0 <= args.label_noise < 1:
        raise ValueError("bad arguments")
    print("Device:", DEVICE, "| dataset:", args.dataset, "| label noise:", args.label_noise,
          "| runs:", args.runs)

    methods = ["SGD", "Adam", "DQN-Online", "DQN-Meta"]
    res = {(s, m): [] for s in scales for m in methods}
    for run in range(args.runs):
        seed = args.seed + run
        print(f"\n========== RUN {run+1}/{args.runs} (seed={seed}) ==========")
        tr, va, te, probe, info = load_data(args.dataset, args.batch_size, seed, args.label_noise)
        meta_agent = meta_train(args, tr, probe, info, seed)
        for s in scales:
            print(f"\n----- lr scale {s}x  (SGD lr={BASE_LR*s:.5f}, Adam lr={ADAM_LR*s:.6f}) -----")
            for m in methods:
                print(f"\n{m}:")
                if m in ("SGD", "Adam"):
                    out = train_baseline(m, s, tr, va, te, args.epochs, seed, info,
                                         args.max_train_batches)
                else:
                    online = (m == "DQN-Online")
                    agent = DQNAgent() if online else meta_agent
                    total = args.epochs * min(len(tr), args.max_train_batches or len(tr))
                    eps_fn = ((lambda st, T=total: max(0.05, 1.0 - st / (0.7 * T))) if online
                              else (lambda st: 0.0))
                    model = fresh_model(seed, info); t0 = time.perf_counter()
                    _, rb, rs, _, _ = run_dqn(agent, model, tr, probe, args.epochs,
                                              args.max_train_batches, BASE_LR * s, eps_fn,
                                              learn=online, val_loader=va, label=m)
                    tl, ta = evaluate(model, te)
                    out = (ta, tl, time.perf_counter() - t0, rb, rs, False)
                res[(s, m)].append(out)
                print(f"TEST {m}: acc={out[0]*100:.2f}% loss={out[1]:.4f} time={out[2]:.0f}s "
                      f"rollbacks={out[3]} resets={out[4]}{' DIVERGED' if out[5] else ''}")

    print("\n" + "=" * 86)
    print(f"FINAL SUMMARY dataset={args.dataset} label_noise={args.label_noise} runs={args.runs}"
          f"  (test accuracy, mean +/- std)")
    print("=" * 86)
    print(f"{'lr scale':<9}{'method':<12}{'test acc':>17}{'worst run':>11}{'rollbacks':>11}{'resets':>8}{'time':>7}")
    for s in scales:
        for m in methods:
            r = res[(s, m)]
            a = np.array([x[0] for x in r]) * 100
            print(f"{s:<9}{m:<12}{a.mean():>9.2f}% +/-{a.std():4.2f}{a.min():>10.2f}%"
                  f"{np.mean([x[3] for x in r]):>11.1f}{np.mean([x[4] for x in r]):>8.1f}"
                  f"{np.mean([x[2] for x in r]):>6.0f}s")
        print("-" * 86)
